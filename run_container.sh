#!/bin/bash

echo "===================================================================================================="
echo "================== ПРОЦЕДУРА РАЗВЕРТЫВАНИЯ VOICE SHIELD API ====================="
echo "===================================================================================================="

# --- ЭТАП 1: СБОРКА ОБРАЗА ---
echo "\n--- НАЧАЛО ЭТАПА 1: СБОРКА DOCKER ОБРАЗА ---\n"
# Эта команда собирает ВСЕ и только необходимые компоненты, игнорируя мусор.
docker build -t voiceshield:latest .

if [ $? -ne 0 ]; then
    echo "❌ КРИТИЧЕСКАЯ ОШИБКА: Сборка Docker Образа НЕ УДАЛАСЬ. Проверьте, что вы в корневом каталоге проекта и что Docker запущен."
    exit 1
fi
echo "✅ Образ voiceshield:latest успешно собран."

echo "\n===================================================================================================="

echo "🚀 2. ЗАПУСК КОНТЕЙНЕРА (Пользователь должен запустить вручную) 🚀"
echo "===================================================================================================="

echo "ВАЖНО: Выполните следующую команду вручную в терминале, чтобы запустить сервис:"
#!/bin/bash

# --- Скрипт для сборки и запуска контейнера VoiceShield API (Финальная, устойчивая версия) ---

echo "============================================================================================"
echo "🚀 1. СБОРКА DOCKER ОБРАЗА (Context: .)"
echo "=================================================================================================="

docker build -t voiceshield:latest .

if [ $? -ne 0 ]; then
    echo "❌ ОШИБКА: Не удалось собрать Docker образ. Проверьте Dockerfile и зависимости."
    exit 1
fi
echo "✅ Образ voiceshield:latest успешно собран."

echo "=================================================================================================="

echo "🚀 2. ЗАПУСК КОНТЕЙНЕРА (API: 8080)"
echo "=================================================================================================="

# Используем -p 8080:8080
docker run -d --name voiceshield_api -p 8080:8080 voiceshield:latest

if [ $? -ne 0 ]; then
    echo "\n!!! КРИТИЧЕСКАЯ ОШИБКА ЗАПУСКА !!!"
    echo "Контейнер НЕ ЗАПУСТИЛСЯ. Проверьте, что порт 8080 свободен на вашей машине."
    echo "Используйте: docker logs voiceshield_api"
    exit 1
fi
echo "==================================================================================================="
echo "✅ УСПЕШНО! API доступен по http://localhost:8080"
echo "====================================================================================================="
echo "Для остановки: docker stop voiceshield_api"
echo "Для полной очистки: docker system prune -a"

if [ $? -ne 0 ]; then
    echo "
--- ВНИМАНИЕ ---"
    echo "Если команда выше завершилась ошибкой, проверьте:
- Порт 8000 занят.
- Установлены все системные зависимости (librosa, sounddevice).
---------------------------------------------------"
    exit 1
fi

echo "===================================================================================================="
echo "✅ ЗАПУСК УСПЕШЕН! API доступен по http://localhost:8000"
echo "===================================================================================================="
echo "ВНИМАНИЕ: При завершении работы используйте:\"
docker stop voiceshield_api && docker rm voiceshield_api\"


